function stored(): Lang {
  try {
    return localStorage.getItem(KEY) === 'ar' ? 'ar' : 'en';
  } catch {
    return 'en';
  }
}

/** Read once at start-up: every screen is built in this language. Changing it reloads the page. */
export const lang: Lang = stored();
export const rtl = lang === 'ar';

export function saveLang(next: Lang): void {
  try {
    localStorage.setItem(KEY, next);
  } catch {
    /* without storage the choice cannot outlive the reload, so nothing changes */
  }
}

/** The string in the player's language, with any `{holes}` filled from `vars`. */
export function tr(text: string, vars?: Readonly<Record<string, string | number>>): string {
  let out = lang === 'ar' ? (AR[text] ?? text) : text;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v));
  return out;
}
