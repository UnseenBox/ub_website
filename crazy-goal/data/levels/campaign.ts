/**
 * The campaign of CRAZY KORA: matches 4 to 40 (match 1 is the tutorial, 2 and 3 are in matches.ts).
 *
 * Every alley has its own outline, its own ground, its own landmarks and its own reason to
 * exist. The nine chapters keep their old names and boundaries; what changed is everything
 * inside them.
 *
 * Coordinates: x runs 450 to 1150, y runs 170 (the goal line) to 1110 (the kerb behind you).
 * The `arena` rectangle is still the camera frame, but the playable ground is the `boundary`
 * outline, so no two levels have to look like the same rectangle.
 *
 * Difficulty follows INTRODUCE -> COMBINE -> TWIST -> EXAM. A level only asks for a mechanic
 * it has already taught, then bends it.
 */

