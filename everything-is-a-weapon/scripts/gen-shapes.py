"""Generates src/ui/shapes.css: the torn-paper silhouettes used all over the UI.
Deterministic (fixed seeds), so re-running it never changes the look by accident."""
import io, math, os, random

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))


def fmt(points):
    return 'polygon(' + ', '.join(f'{x:.1f}% {y:.1f}%' for x, y in points) + ')'


def torn(seed, top=0.6, right=1.6, bottom=0.6, left=1.6, steps_h=9, steps_v=5):
    """A rectangle whose edges wander inwards by up to the given percentage."""
    rnd = random.Random(seed)
    pts = []
    for i in range(steps_h):
        pts.append((100 * i / steps_h, rnd.uniform(0, top)))
    for i in range(steps_v):
        pts.append((100 - rnd.uniform(0, right), 100 * i / steps_v))
    for i in range(steps_h):
        pts.append((100 - 100 * i / steps_h, 100 - rnd.uniform(0, bottom)))
    for i in range(steps_v):
        pts.append((rnd.uniform(0, left), 100 - 100 * i / steps_v))
    return fmt(pts)


def burst(points=18, inner=74, seed=3):
    rnd = random.Random(seed)
    pts = []
    for i in range(points * 2):
        a = math.tau * i / (points * 2) - math.pi / 2
        r = 50 if i % 2 == 0 else inner / 2 + rnd.uniform(-2, 2)
        pts.append((50 + math.cos(a) * r, 50 + math.sin(a) * r))
    return fmt(pts)


def zigzag(teeth=13, depth='7px'):
    parts = ['0 0', '100% 0']
    for i in range(teeth * 2 + 1):
        x = 100 - 100 * i / (teeth * 2)
        y = '100%' if i % 2 == 0 else f'calc(100% - {depth})'
        parts.append(f'{x:.2f}% {y}')
    return 'polygon(' + ', '.join(parts) + ')'


def tape():
    left = [(0, 0), (4, 18), (0.5, 36), (4.5, 55), (0, 74), (3.5, 100)]
    right = [(96.5, 100), (100, 80), (95.5, 60), (99.5, 42), (96, 22), (100, 0)]
    return fmt(left + right)


lines = [
    '/* Generated by scripts/gen-shapes.py. Torn-paper silhouettes as clip paths. */',
    ':root {',
    f'  --torn-strip-a: {torn(11, 6, 2.2, 8, 2.4)};',
    f'  --torn-strip-b: {torn(23, 8, 2.6, 5, 1.8)};',
    f'  --torn-strip-c: {torn(37, 4, 1.8, 9, 2.8)};',
    f'  --torn-note: {torn(5, 2.2, 1.6, 3, 1.4, 6, 6)};',
    f'  --torn-page: {torn(8, 0.8, 0.8, 1, 0.8, 14, 14)};',
    f'  --torn-card: {torn(15, 2, 1.2, 2.5, 1.2, 7, 5)};',
    f'  --cut-a: polygon(3% 7%, 97% 0%, 100% 92%, 0% 100%);',
    f'  --cut-b: polygon(0% 0%, 100% 6%, 95% 100%, 4% 95%);',
    f'  --cut-c: polygon(5% 0%, 100% 3%, 97% 97%, 0% 100%);',
    f'  --zigzag: {zigzag()};',
    f'  --burst: {burst()};',
    f'  --tape-shape: {tape()};',
    '}',
    '',
]
io.open('src/ui/shapes.css', 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('shapes written')
